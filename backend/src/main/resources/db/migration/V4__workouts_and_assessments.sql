CREATE TABLE workouts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version bigint NOT NULL DEFAULT 0,
 name varchar(120) NOT NULL, student_id bigint NOT NULL REFERENCES students(id), teacher_id bigint NOT NULL REFERENCES teachers(id),
 issued_on date NOT NULL, notes varchar(2000) NOT NULL, active boolean NOT NULL DEFAULT true
);
CREATE INDEX workouts_student_idx ON workouts(student_id,issued_on DESC);
CREATE TABLE workout_exercises (
 workout_id bigint NOT NULL REFERENCES workouts(id) ON DELETE CASCADE, position integer NOT NULL,
 name varchar(120) NOT NULL, sets integer NOT NULL CHECK(sets BETWEEN 1 AND 30), repetitions varchar(40) NOT NULL,
 load_kg numeric(6,2) NOT NULL CHECK(load_kg BETWEEN 0 AND 1000), rest_seconds integer NOT NULL CHECK(rest_seconds BETWEEN 0 AND 1800), notes varchar(500) NOT NULL,
 PRIMARY KEY(workout_id,position)
);
CREATE TABLE assessments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version bigint NOT NULL DEFAULT 0,
 student_id bigint NOT NULL REFERENCES students(id), assessed_on date NOT NULL,
 weight_kg numeric(5,2) NOT NULL CHECK(weight_kg BETWEEN 1 AND 500),height_cm numeric(5,2) NOT NULL CHECK(height_cm BETWEEN 30 AND 260),
 waist_cm numeric(5,2) CHECK(waist_cm BETWEEN 1 AND 300), chest_cm numeric(5,2) CHECK(chest_cm BETWEEN 1 AND 300),hip_cm numeric(5,2) CHECK(hip_cm BETWEEN 1 AND 300),notes varchar(2000) NOT NULL
);
CREATE INDEX assessments_student_idx ON assessments(student_id,assessed_on DESC);
