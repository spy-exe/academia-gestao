CREATE TABLE plans (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version bigint NOT NULL DEFAULT 0,
 name varchar(100) NOT NULL, price numeric(12,2) NOT NULL CHECK(price>0),
 period_months integer NOT NULL CHECK(period_months IN (1,3,6,12)), benefits varchar(2000) NOT NULL, active boolean NOT NULL DEFAULT true
);
CREATE TABLE students (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version bigint NOT NULL DEFAULT 0,
 name varchar(120) NOT NULL, email varchar(180) NOT NULL, phone varchar(30) NOT NULL,
 birth_date date NOT NULL, enrollment_date date NOT NULL, plan_id bigint REFERENCES plans(id), active boolean NOT NULL DEFAULT true,
 CHECK(birth_date < enrollment_date)
);
CREATE INDEX students_name_idx ON students(lower(name));
CREATE TABLE teachers (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version bigint NOT NULL DEFAULT 0,
 name varchar(120) NOT NULL, email varchar(180) NOT NULL, phone varchar(30) NOT NULL,
 specialties varchar(500) NOT NULL, registration varchar(40) UNIQUE, active boolean NOT NULL DEFAULT true
);
