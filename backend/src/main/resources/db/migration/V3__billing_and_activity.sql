CREATE TABLE invoices (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id bigint NOT NULL REFERENCES students(id),
 competence date NOT NULL CHECK(EXTRACT(DAY FROM competence)=1),
 due_date date NOT NULL, amount numeric(12,2) NOT NULL CHECK(amount>0),
 period_months integer NOT NULL CHECK(period_months IN (1,3,6,12)),
 paid_on date, created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(student_id,competence)
);
CREATE INDEX invoices_due_idx ON invoices(due_date) WHERE paid_on IS NULL;
CREATE INDEX invoices_paid_idx ON invoices(paid_on) WHERE paid_on IS NOT NULL;
CREATE TABLE activities (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor varchar(180) NOT NULL, description varchar(300) NOT NULL, occurred_at timestamptz NOT NULL DEFAULT now()
);
